"""Builds visualizations/javascript/zeta_uns_path_data.js for the browser page webgl_aizawa_vs_zeta_uns.html.
Uses the engine ValaQuenta/modules/zeta_uns_path (Riemann-Siegel path, 16 samples per zero spacing, the first 25,000 zeros) and data/zeros_25000_hp.tsv.
The data ride in a <script> file as base64 Float32 arrays: Firefox blocks fetch() of file:// pages, a <script src> works offline."""
import base64, json, sys, pathlib, time
root = pathlib.Path(__file__).resolve().parents[1]; sys.path.insert(0, str(root.parent))
import numpy as np
from ValaQuenta.modules.zeta_uns_path import maths as M
t0 = time.time(); NZ = 25000
g = np.array([float(l.split()[1]) for l in open(root / 'data/zeros_25000_hp.tsv') if l[0].isdigit()])[:NZ]
ts = M.sample_by_phase(10.0, NZ, 16, jitter=True); z = M.zeta_line(ts); print('path', len(ts), 'points', round(time.time() - t0, 1), 's; t to', ts[-1], '; zeros', len(g), g[-1])
xs = np.linspace(0.3, 5.0, 1800); S = np.concatenate([np.mean(np.cos(np.outer(xs[i:i + 100], g)), axis=1) for i in range(0, len(xs), 100)])
b64 = lambda a: base64.b64encode(np.asarray(a, np.float32).tobytes()).decode()
out = root / 'visualizations/javascript/zeta_uns_path_data.js'
with open(out, 'w') as f:
    f.write('// generated by experiments/build_zeta_uns_viz_data.py: Riemann-Siegel path of zeta(1/2+it), t from 10, 16 samples per zero spacing; zeros; zero spectrum. Not hand-edited.\n')
    f.write('window.ZETA_UNS = {n: %d, nz: %d, tmax: %.6f, t: "%s", re: "%s", im: "%s", zeros: "%s", specx: "%s", spec: "%s"};\n' % (len(ts), len(g), ts[-1], b64(ts), b64(z.real), b64(z.imag), b64(g), b64(xs), b64(S)))
print(out, round(out.stat().st_size / 1e6, 2), 'MB')
